const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context={document:{getElementById:()=>({})},location:{pathname:'/competicao.php',search:''}};
let source=fs.readFileSync('assets/js/match-details.js','utf8');
source=source.slice(0,source.indexOf("document.addEventListener('click'"))+"globalThis.renderGame=renderGame;})();";
vm.runInNewContext(source,context);
const match={time_a_id:1,time_b_id:2,time_a:'Lords FC',time_b:'Gari Saint German',gols_a:3,gols_b:2,status:'finalizada'};
const summary={score_only:true,home_name:'Gari Saint German',away_name:'Lords FC',duration:null,man_of_match:'Thiago Neves',teams:[{code:'GSG',scorers:[{player:'Memphis Depay',goals:2}]},{code:'LOR',scorers:[{player:'Iniesta',goals:3}]}],events:[]};
const html=context.renderGame(match,summary);
assert.match(html,/Partida sem súmula/);
assert.match(html,/3 × 2/);
assert.match(html,/Iniesta.*3 gols/);
assert.match(html,/data-player-team="1">Iniesta/);
assert.match(html,/data-player-team="2">Memphis Depay/);
assert.ok(!/Lances da partida|null|Craque:|assistência/.test(html));
const normal=context.renderGame(match,{...summary,score_only:false,teams:summary.teams.map(t=>({...t,stats:{}})),events:[{type:'goal',player:'Iniesta',team_code:'LOR',minute:'30',assist:'Rodri'}]});
assert.match(normal,/Lances da partida/);
assert.match(normal,/30'/);
assert.match(normal,/assistência/);
console.log('Score-only match details tests passed.');
